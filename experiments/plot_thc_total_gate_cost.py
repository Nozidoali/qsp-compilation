"""Plot THC total gate cost vs THC rank M.

Input CSV is expected from experiments.compare_thc_total_gate_cost and uses:

    total_gate_cost = CNOT + T + H + S

Usage
-----
    python -m experiments.plot_thc_total_gate_cost
    python -m experiments.plot_thc_total_gate_cost -i thc_total_gate_cost.csv -o thc_total_gate_cost.png
"""
from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path
from typing import Dict, List, Tuple

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


STYLE = {
    "sparse": {"color": "#1565C0", "marker": "o", "ls": "-", "label": "Sparse rotation"},
    "dense": {"color": "#6A1B9A", "marker": "s", "ls": "-", "label": "Dense rotation"},
    "qrom": {"color": "#C62828", "marker": "^", "ls": "--", "label": "QROM"},
    "selectswap": {"color": "#E65100", "marker": "D", "ls": "--", "label": "Select-swap"},
}


def parse_bool(value: str) -> bool:
    return value.strip().lower() in {"1", "true", "yes", "y"}


def read_rows(path: Path) -> List[dict]:
    rows: List[dict] = []
    with open(path) as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            row["M"] = int(row["M"])
            row["n"] = int(row["n"])
            row["m"] = int(row["m"])
            row["precision_bits"] = int(row["precision_bits"])
            row["total_gate_cost"] = int(row["total_gate_cost"])
            row["success"] = parse_bool(row["success"])
            rows.append(row)
    return rows


def choose_precision(rows: List[dict], requested: int | None) -> int:
    if requested is not None:
        return requested
    available = sorted(set(r["precision_bits"] for r in rows))
    if not available:
        raise ValueError("No precision values found in input rows.")
    return available[-1]


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Plot total gate cost (CNOT+T+H+S) for THC benchmark states."
    )
    parser.add_argument(
        "-i",
        "--input",
        type=Path,
        default=Path("thc_total_gate_cost.csv"),
        help="Input CSV generated by compare_thc_total_gate_cost.",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("thc_total_gate_cost.png"),
        help="Output image file.",
    )
    parser.add_argument(
        "--source",
        choices=("approximated", "exact", "all"),
        default="approximated",
        help="Which source subset to plot.",
    )
    parser.add_argument(
        "--family",
        choices=("li", "reiher", "all"),
        default="all",
        help="Which FeMoco family subset to plot.",
    )
    parser.add_argument(
        "--approaches",
        default="sparse,qrom,selectswap",
        help="Comma-separated approaches to include.",
    )
    parser.add_argument(
        "--precision",
        type=int,
        default=None,
        help="Precision bits to plot. Default: highest precision in CSV.",
    )
    parser.add_argument(
        "--include-failed",
        action="store_true",
        help="Include failed synthesis rows in the plot.",
    )
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    if not args.input.exists():
        raise FileNotFoundError(
            f"{args.input} not found. Run: python -m experiments.compare_thc_total_gate_cost"
        )

    rows = read_rows(args.input)
    precision = choose_precision(rows, args.precision)
    approaches = [x.strip() for x in args.approaches.split(",") if x.strip()]

    filtered: List[dict] = []
    for row in rows:
        if row["precision_bits"] != precision:
            continue
        if args.source != "all" and row["source"] != args.source:
            continue
        if args.family != "all" and row["family"] != args.family:
            continue
        if row["approach"] not in approaches:
            continue
        if not args.include_failed and not row["success"]:
            continue
        filtered.append(row)

    if not filtered:
        raise ValueError("No rows left after filtering. Adjust --source/--family/--precision.")

    families = sorted(set(row["family"] for row in filtered))
    ncols = len(families)
    fig, axes = plt.subplots(1, ncols, figsize=(6 * ncols, 5), squeeze=False)

    for col, family in enumerate(families):
        ax = axes[0][col]
        by_approach: Dict[str, List[Tuple[int, int]]] = defaultdict(list)
        for row in filtered:
            if row["family"] != family:
                continue
            by_approach[row["approach"]].append((row["M"], row["total_gate_cost"]))

        for approach in approaches:
            points = by_approach.get(approach, [])
            if not points:
                continue
            points = sorted(points, key=lambda t: t[0])
            xs = [p[0] for p in points]
            ys = [p[1] for p in points]
            style = STYLE.get(
                approach,
                {"color": "#333333", "marker": "o", "ls": "-", "label": approach},
            )
            ax.plot(
                xs,
                ys,
                marker=style["marker"],
                linestyle=style["ls"],
                color=style["color"],
                label=style["label"],
                linewidth=1.8,
                markersize=5,
                alpha=0.9,
            )

        ax.set_xlabel("THC rank M")
        ax.set_ylabel("Total gate cost (CNOT + T + H + S)")
        ax.set_title(f"{family.capitalize()} FeMoco")
        ax.set_yscale("log")
        ax.grid(True, alpha=0.25, which="major")
        ax.grid(True, alpha=0.1, which="minor")
        ax.legend(fontsize=9, loc="best")

    source_label = args.source if args.source != "all" else "all sources"
    fig.suptitle(
        f"THC Total Gate Cost vs M (precision={precision}, source={source_label})",
        fontsize=13,
        fontweight="bold",
        y=1.02,
    )
    plt.tight_layout()
    fig.savefig(args.output, dpi=180, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved plot to {args.output}")


if __name__ == "__main__":
    main()
